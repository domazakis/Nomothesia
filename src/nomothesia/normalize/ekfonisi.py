"""Μετατροπή νομικού κειμένου σε μορφή που διαβάζεται σωστά από φωνή.

Το ΦΕΚ γράφει για το μάτι: «παρ. 2 περ. β΄ του π.δ. 237/1986 (Α΄ 110)». Ένα
σύστημα σύνθεσης ομιλίας διαβάζει «παρ», «περ», «πι δέλτα» — ή τα καταπίνει.
Ο αναγνώστης καταλαβαίνει· ο ακροατής όχι.

Εδώ ανοίγουν οι συντομογραφίες: «παράγραφος 2, περίπτωση βήτα του προεδρικού
διατάγματος 237 του 1986». Το νόημα δεν αλλάζει, ο τρόπος γραφής αλλάζει.

Δύο κανόνες διέπουν τον σχεδιασμό:

* **Καμία αντικατάσταση χωρίς συμφραζόμενα.** Το «ν.» γίνεται «νόμος» μόνο όταν
  ακολουθεί αριθμός. Αλλιώς θα άλλαζε κάθε λέξη που τυχαίνει να τελειώνει σε
  νι πριν από τελεία.
* **Ό,τι δεν είναι σίγουρο, μένει.** Το κείμενο είναι νομοθεσία· μια λάθος
  «διόρθωση» είναι χειρότερη από μια συντομογραφία που ακούγεται άσχημα.
"""

from __future__ import annotations

import re

# Ελληνικά γράμματα με κεραία, όπως τα προφέρουμε. Χρησιμοποιούνται τόσο για
# τεύχη ΦΕΚ («Α΄ 110») όσο και για περιπτώσεις άρθρων («περ. β΄»).
GRAMMATA = {
    "α": "άλφα", "β": "βήτα", "γ": "γάμμα", "δ": "δέλτα", "ε": "έψιλον",
    "στ": "στίγμα", "ζ": "ζήτα", "η": "ήτα", "θ": "θήτα", "ι": "γιώτα",
    "κ": "κάππα", "λ": "λάμδα", "μ": "μι", "ν": "νι", "ξ": "ξι",
    "ο": "όμικρον", "π": "πι", "ρ": "ρο", "σ": "σίγμα", "τ": "ταυ",
    "υ": "ύψιλον", "φ": "φι", "χ": "χι", "ψ": "ψι", "ω": "ωμέγα",
}

# Είδη νομοθετημάτων: η συντομογραφία και το πλήρες όνομα στη γενική, όπως
# εμφανίζεται στις παραπομπές («του προεδρικού διατάγματος 237»).
NOMOTHETIMATA = (
    (r"ν\.δ\.", "νομοθετικού διατάγματος"),
    (r"π\.δ\.", "προεδρικού διατάγματος"),
    (r"κ\.υ\.α\.?", "κοινής υπουργικής απόφασης"),
    (r"υ\.α\.", "υπουργικής απόφασης"),
    (r"ν\.", "νόμου"),
    (r"α\.ν\.", "αναγκαστικού νόμου"),
)

# Συντομογραφίες που ακολουθούνται από αριθμό ή γράμμα.
ME_ARITHMO = (
    (r"παρ\.", "παράγραφος"),
    (r"περ\.", "περίπτωση"),
    (r"υποπερ\.", "υποπερίπτωση"),
    (r"εδ\.", "εδάφιο"),
    (r"άρθρ\.", "άρθρο"),
    (r"αρ\.", "αριθμός"),
    (r"σελ\.", "σελίδα"),
)

# Αυτοτελείς συντομογραφίες, χωρίς εξάρτηση από ό,τι ακολουθεί.
AFTOTELEIS = (
    (r"κ\.λπ\.", "και λοιπά"),
    (r"κ\.ά\.", "και άλλα"),
    (r"κ\.ο\.κ\.", "και ούτω καθεξής"),
    (r"π\.χ\.", "για παράδειγμα"),
    (r"βλ\.", "βλέπε"),
    (r"χλμ/ώρα", "χιλιόμετρα την ώρα"),
    (r"χλμ/ω", "χιλιόμετρα την ώρα"),
    (r"χλμ\.?", "χιλιόμετρα"),
    (r"γρ\./λίτρο", "γραμμάρια ανά λίτρο"),
    (r"κ\.εκ\.", "κυβικά εκατοστά"),
    # Το ΦΕΚ επαναλαμβάνει τις μονάδες και λατινικά, σε παρένθεση.
    (r"gr\./l\b", "γραμμάρια ανά λίτρο"),
    (r"km/h\b", "χιλιόμετρα την ώρα"),
    (r"mg/l\b", "χιλιοστά του γραμμαρίου ανά λίτρο"),
    (r"τ\.μ\.", "τετραγωνικά μέτρα"),
)


def _grammata_me_keraia(keimeno: str) -> str:
    """«περ. β΄» → «περίπτωση βήτα», «Μέρος Α΄» → «Μέρος Άλφα»."""

    def antikatastasi(m: re.Match[str]) -> str:
        gramma = m.group(1)
        onoma = GRAMMATA.get(gramma.lower())
        if not onoma:
            return m.group(0)
        return onoma.capitalize() if gramma[0].isupper() else onoma

    return re.sub(r"\b(στ|[Α-Ωα-ω])[΄']", antikatastasi, keimeno)


def _arithmoi_nomothetimaton(keimeno: str) -> str:
    """«237/1986» → «237 του 1986», μόνο όταν μοιάζει με αριθμό νομοθετήματος.

    Το έτος πρέπει να είναι τετραψήφιο και να ξεκινά με 1 ή 2, ώστε να μην
    πειραχτούν κλάσματα, αναλογίες ή αριθμοί πρωτοκόλλου.
    """
    return re.sub(r"\b(\d{1,5})/((?:19|20)\d{2})\b", r"\1 του \2", keimeno)


def gia_ekfonisi(keimeno: str) -> str:
    """Επιστρέφει το κείμενο γραμμένο όπως προφέρεται."""
    for syntomografia, plires in NOMOTHETIMATA:
        # Μόνο όταν ακολουθεί αριθμός: αλλιώς δεν πρόκειται για παραπομπή.
        keimeno = re.sub(
            rf"(?<![Α-Ωα-ωA-Za-z]){syntomografia}\s*(?=\d)", f"{plires} ", keimeno
        )

    for syntomografia, plires in ME_ARITHMO:
        keimeno = re.sub(
            rf"(?<![Α-Ωα-ωA-Za-z]){syntomografia}\s*(?=[\dΑ-Ωα-ω])", f"{plires} ", keimeno
        )

    for syntomografia, plires in AFTOTELEIS:
        keimeno = re.sub(rf"(?<![Α-Ωα-ωA-Za-z]){syntomografia}", plires, keimeno)

    keimeno = _grammata_me_keraia(keimeno)
    keimeno = _arithmoi_nomothetimaton(keimeno)

    keimeno = keimeno.replace("%", " τοις εκατό").replace("€", " ευρώ")
    # Οι αντικαταστάσεις αφήνουν διπλά κενά· μια φωνή δεν τα ακούει, ένας
    # άνθρωπος που ελέγχει το αρχείο τα βλέπει.
    return re.sub(r"[ \t]{2,}", " ", keimeno).strip()
